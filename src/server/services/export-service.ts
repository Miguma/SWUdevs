import { MeetingExtraction, ActionItem } from "@/types/meeting";
import { formatDateDisplay } from "@/lib/utils";

export interface ExportOptions {
  includePending?: boolean;
}

export function generateMarkdownExport(
  meeting: MeetingExtraction,
  options: ExportOptions = {}
): string {
  const { includePending = false } = options;

  // Filter tasks: default to approved only, or include pending if requested.
  // Never include rejected tasks!
  const tasksToExport = meeting.actionItems.filter((t) => {
    if (t.reviewStatus === "approved") return true;
    if (includePending && t.reviewStatus === "pending") return true;
    return false;
  });

  const decisionsToExport = meeting.decisions.filter((d) => {
    if (d.reviewStatus === "approved") return true;
    if (includePending && d.reviewStatus === "pending") return true;
    return false;
  });

  const questionsToExport = meeting.openQuestions.filter((q) => {
    if (q.reviewStatus === "approved") return true;
    if (includePending && q.reviewStatus === "pending") return true;
    return false;
  });

  const lines: string[] = [];

  // Header & Metadata
  lines.push(`# ${meeting.title}`);
  if (meeting.organization) {
    lines.push(`**Organization / Team:** ${meeting.organization}`);
  }
  lines.push(
    `**Meeting Date:** ${
      meeting.meetingDate ? formatDateDisplay(meeting.meetingDate) : "Not specified"
    } (${meeting.timezone})`
  );
  lines.push(`**Generated by:** Tambayayong — From conversation to action.`);
  lines.push("");

  // Summary
  if (meeting.summary) {
    lines.push("## Meeting Summary");
    lines.push(meeting.summary);
    lines.push("");
  }

  // Action Items
  lines.push("## Action Items");
  if (tasksToExport.length === 0) {
    lines.push("*No approved action items recorded.*");
  } else {
    for (const task of tasksToExport) {
      const pendingTag = task.reviewStatus === "pending" ? " `[PENDING REVIEW]`" : "";
      const priorityTag = task.priority ? ` [Priority: ${task.priority.toUpperCase()}]` : "";
      lines.push(`- [ ] **${task.title}**${priorityTag}${pendingTag}`);

      if (task.description) {
        lines.push(`  - Context: ${task.description}`);
      }

      const owners =
        task.assignees.length > 0 ? task.assignees.join(", ") : "Unassigned";
      lines.push(`  - Owner: ${owners}`);

      const due = task.deadline.date
        ? `${task.deadline.date}${task.deadline.time ? ` at ${task.deadline.time}` : ""}`
        : task.deadline.originalText || "Not specified";
      const relation = task.deadline.relation ? ` (${task.deadline.relation})` : "";
      lines.push(`  - Due: ${due}${relation}`);

      if (task.evidence && task.evidence.length > 0 && task.evidence[0].quote) {
        lines.push(`  - Source (${task.evidence[0].provenance || "unverified"}${task.isUserEdited ? "; item edited by reviewer" : ""}): _"${task.evidence[0].quote}"_`);
      }
      lines.push("");
    }
  }
  lines.push("");

  // Decisions
  lines.push("## Confirmed Decisions");
  if (decisionsToExport.length === 0) {
    lines.push("*No decisions recorded.*");
  } else {
    for (const dec of decisionsToExport) {
      const pendingTag = dec.reviewStatus === "pending" ? " `[PENDING REVIEW]`" : "";
      lines.push(`- ${dec.decision}${pendingTag}`);
      if (dec.evidence && dec.evidence.length > 0 && dec.evidence[0].quote) {
        lines.push(`  - _Evidence (${dec.evidence[0].provenance || "unverified"}): "${dec.evidence[0].quote}"_`);
      }
    }
  }
  lines.push("");

  // Open Questions & Follow-ups
  lines.push("## Unresolved Questions & Follow-ups");
  if (questionsToExport.length === 0) {
    lines.push("*No open questions recorded.*");
  } else {
    for (const q of questionsToExport) {
      const pendingTag = q.reviewStatus === "pending" ? " `[PENDING REVIEW]`" : "";
      lines.push(`- ❓ ${q.question}${pendingTag}`);
      if (q.evidence && q.evidence.length > 0 && q.evidence[0].quote) {
        lines.push(`  - _Evidence (${q.evidence[0].provenance || "unverified"}): "${q.evidence[0].quote}"_`);
      }
    }
  }
  lines.push("");

  // Next Meeting
  if (meeting.nextMeeting && (meeting.nextMeeting.date || meeting.nextMeeting.originalText)) {
    lines.push("## Next Meeting");
    const nextDue = meeting.nextMeeting.date
      ? `${meeting.nextMeeting.date}${meeting.nextMeeting.time ? ` at ${meeting.nextMeeting.time}` : ""}`
      : meeting.nextMeeting.originalText;
    lines.push(`- Scheduled: ${nextDue}`);
    lines.push("");
  }

  return lines.join("\n");
}

export function sanitizeCsvField(value: any): string {
  if (value === null || value === undefined) return '""';
  let str = String(value);

  // Formula Injection Defense (CWE-1236)
  // If field starts with =, +, -, @, \t, or \r, prepend single quote
  if (/^[\s\uFEFF]*[=+@-]/.test(str) || /^[\t\r\n]/.test(str)) {
    str = "'" + str;
  }

  // Escape double quotes
  const escaped = str.replace(/"/g, '""');
  return `"${escaped}"`;
}

export function generateCsvExport(
  meeting: MeetingExtraction,
  options: ExportOptions = {}
): string {
  const { includePending = false } = options;

  const tasksToExport = meeting.actionItems.filter((t) => {
    if (t.reviewStatus === "approved") return true;
    if (includePending && t.reviewStatus === "pending") return true;
    return false;
  });

  const headers = [
    "Meeting Title",
    "Task Title",
    "Description",
    "Assignees",
    "Deadline",
    "Original Deadline Text",
    "Commitment Status",
    "Priority",
    "Review Status",
    "Source Evidence",
    "Source Provenance",
    "User Edited",
    "Deadline Relation",
    "Deadline Time",
    "Deadline Timezone",
  ];

  const rows: string[] = [headers.map(sanitizeCsvField).join(",")];

  for (const task of tasksToExport) {
    const row = [
      meeting.title,
      task.title,
      task.description || "",
      task.assignees.join("; "),
      task.deadline.date || "",
      task.deadline.originalText || "",
      task.commitmentStatus,
      task.priority || "",
      task.reviewStatus,
      task.evidence.map((e) => e.quote).filter(Boolean).join(" | "),
      task.evidence.map((e) => e.provenance || "unverified").join(" | "),
      task.isUserEdited ? "yes" : "no",
      task.deadline.relation || "",
      task.deadline.time || "",
      task.deadline.timezone,
    ];
    rows.push(row.map(sanitizeCsvField).join(","));
  }

  return rows.join("\r\n");
}
